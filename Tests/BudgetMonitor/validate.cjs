const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root, 'DeviceActivityMonitorExtension/DeviceActivityMonitorExtension.swift'), 'utf8');
const enforcement = source.split('private func enforceDailyBudget(')[1].split('private struct BudgetContext')[0];
assert.match(enforcement, /BudgetMonitorRearm.run\(expected: state/);
assert.doesNotMatch(enforcement, /startNextChunkMonitoring\(/, 'Daily budget must not use the legacy Boolean failure path');
assert.match(enforcement, /guard context.selection == data else \{ return \}/);
assert.match(enforcement, /FamilyAccessStore.allowed && DailyBudgetStore.shared.isEnabled/);
assert.match(enforcement, /budgetContext\(defaults\) == context && !budgetTemporarilyBlocked\(defaults\)/);
assert.match(enforcement, /DailyBudgetStore.shared.current\(\)\) == expected/);
assert.match(enforcement, /case \.superseded:[\s\S]*?return\s*case \.failed/);
const skipped = enforcement.split('case .superseded:')[1].split('case .failed')[0];
assert.doesNotMatch(skipped, /applyShield\(|clearShield\(|stopMonitoring\(/, 'Obsolete work must not write restrictions');
assert.match(enforcement, /case \.failed\(let expected, let code\):\s*guard current\(expected\) else \{ return \}/);
assert.match(enforcement, /shield\.monitor_failed[\s\S]*applyShield\(selection: selection, ifCurrent: \{ current\(expected\) \}\)/);
assert.match(enforcement, /if state.availableSeconds == 0[\s\S]*shield\.budget_exhausted/);
assert.match(enforcement, /shield\.budget_unavailable[\s\S]*ifCurrent: stillMissing/);
const shield = source.split('private func applyShield(')[1].split('private func clearShield')[0];
assert.equal((shield.match(/!ifCurrent\(\)/g) || []).length, 3, 'Fence each separate shield setter');
assert.doesNotMatch(enforcement, /URLSession|Task\s*\{|Timer|NSLock|withLock/, 'No extra requests, polling, threads or locks around system IPC');
assert.match(source, /parentalcontrol\.budgetMonitorDiagnostic/);
console.log('Budget monitor fallback, access, manual control and no-extra-load guards passed');
