const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const app = read('ParentalControl/App/AppState.swift');
const method = app.slice(app.indexOf('    func prepareRecoveredSetup()'), app.indexOf('    /// One read on reinstall;'));
assert.ok(method.length > 1000);
assert.doesNotMatch(method, /setParentPin|changeDailyBudget|applyInitialParentDailyLimit|unlinkDevices|Timer|Task\.sleep/);
assert.match(method, /accessStatus\(ready: false\)/);
assert.match(method, /role == \.parent && configurationAllowed/);
assert.match(app, /func completeOnboarding\(\) \{\s+setRecoverySetupFamily\(nil\)/);
assert.match(app, /func clearPairing\(\) \{\s+setRecoverySetupFamily\(nil\)/);
const view = read('ParentalControl/Views/Onboarding/RecoverySetupView.swift');
assert.match(view, /guard !loading, steps == nil/);
assert.match(view, /plan\.isEmpty \{ appState\.completeOnboarding\(\)/);
assert.match(view, /failed = true/);
assert.match(view, /guard let plan = try await appState.prepareRecoveredSetup\(\) else \{ return \}/);
assert.match(view, /Button\("setup.back"\)/);
assert.match(view, /await appState.returnToFamilyRecovery\(\)/);
assert.match(method, /let registration = try await remoteSyncService.inspectDeviceRegistration\(\)/);
const flow = read('ParentalControl/Views/Onboarding/OnboardingFlowView.swift');
assert.match(flow, /case \.install:\s+AppInstallQRCodeView\(\)/);
assert.match(flow, /L10n\.f\("recovery.install.body", AppStoreLinks.shareURL.absoluteString, L10n.tr\("recovery.restore"\)\)/);
assert.match(flow, /step == \.install && recoverySteps != nil.*recovery.install.continue/);
assert.match(flow, /recoverySteps == nil && \(step == \.pin \|\| step == \.limit\)/);
assert.match(flow, /guard appState\.isParentModeActive else \{ showsPinEntry = true; return \}/);
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'parental-recovery-setup-'));
fs.writeFileSync(path.join(dir, 'main.swift'), read('Tests/RecoverySetup/cases.swift').replace('// ACTUAL_PREPARATION', method));
execFileSync('xcrun', ['swiftc', '-module-cache-path', '/private/tmp/parental-access-module-cache',
  path.join(root, 'ParentalControl/Models/RecoverySetupPlan.swift'), path.join(dir, 'main.swift'), '-o', path.join(dir, 'tests')], { stdio: 'inherit' });
execFileSync(path.join(dir, 'tests'), { stdio: 'inherit' });
